"""Builds the self-contained, single-file distribution of the simulator.

Usage:
    python3 tools/build_standalone.py            # writes dist/aperion-v0.3.3-standalone.html
    python3 tools/build_standalone.py --check    # exit 1 if the existing file is out of date

The modular application in site/ is the source of truth (decision B5). This script reads
site/index.html and replaces, in place and in the same order:
  - each <link rel="stylesheet" href="css/..."> with a <style> block holding that file,
  - each <script src="js/..."></script> with a <script> block holding that file,
  - each <img src="assets/..."> path with an embedded data: URI.
Nothing else in the page changes. The output has no external references, so it can be opened
directly from disk (e.g. in Microsoft Edge), emailed, or hosted as one file.

The build is deterministic: the same sources always produce the same bytes (no timestamps).
A comment at the top lists the SHA-256 of every source file that was inlined.
Requires only the Python standard library.
"""
import base64
import hashlib
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SITE = ROOT / "site"
VERSION = "0.4.0"
OUT = ROOT / "dist" / f"aperion-v{VERSION}-standalone.html"
MIME = {".png": "image/png", ".jpg": "image/jpeg", ".jpeg": "image/jpeg", ".webp": "image/webp", ".svg": "image/svg+xml"}


def sha(b):
    return hashlib.sha256(b).hexdigest()


def build():
    html = (SITE / "index.html").read_text(encoding="utf-8")
    manifest = []

    def read(rel, binary=False):
        path = (SITE / rel).resolve()
        if SITE.resolve() not in path.parents:
            raise SystemExit(f"Refusing to inline a file outside site/: {rel}")
        data = path.read_bytes()
        if rel not in [m[0] for m in manifest]:
            manifest.append((rel, sha(data)))
        return data if binary else data.decode("utf-8")

    def css(m):
        text = read(m.group(1))
        if "</style" in text.lower():
            raise SystemExit(f"{m.group(1)} contains '</style', which cannot be inlined safely")
        return f'<style data-source="{m.group(1)}">\n{text}</style>'

    def js(m):
        text = read(m.group(1))
        if "</script" in text.lower():
            raise SystemExit(f"{m.group(1)} contains '</script', which cannot be inlined safely")
        return f'<script data-source="{m.group(1)}">\n{text}</script>'

    def img(m):
        rel = m.group(2)
        ext = pathlib.Path(rel).suffix.lower()
        data = read(rel, binary=True)
        return f'{m.group(1)}data:{MIME[ext]};base64,{base64.b64encode(data).decode("ascii")}"'

    out, n_css = re.subn(r'<link rel="stylesheet" href="(css/[^"]+)">', css, html)
    out, n_js = re.subn(r'<script src="(js/[^"]+)"></script>', js, out)
    out, n_img = re.subn(r'(<img[^>]*?\ssrc=")(assets/[^"]+)"', img, out)

    markup = re.sub(r"<script[^>]*>.*?</script>", "", out, flags=re.S)  # code may build src="${...}" strings
    leftovers = re.findall(r'(?:src|href)="(?!data:|#|https?:)[^"]+"', markup)
    if leftovers:
        raise SystemExit(f"External references remain after inlining: {leftovers}")

    header = ["<!--", f"  Aperion Enterprise Data Intelligence Simulator v{VERSION} - standalone single-file build.",
              "  Generated by tools/build_standalone.py from site/. Do not edit this file; edit site/ and rebuild.",
              "  Source files (SHA-256):"]
    header += [f"    {h}  {rel}" for rel, h in manifest]
    header.append("-->")
    if not out.lower().startswith("<!doctype html>"):
        raise SystemExit("site/index.html must start with <!DOCTYPE html>")
    first_line_end = out.index(">") + 1
    out = out[:first_line_end] + "\n" + "\n".join(header) + out[first_line_end:]
    return out, (n_css, n_js, n_img), manifest


def main():
    out, counts, manifest = build()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != out:
            print(f"{OUT.relative_to(ROOT)} is missing or out of date. Run: python3 tools/build_standalone.py")
            sys.exit(1)
        print(f"{OUT.relative_to(ROOT)} is up to date.")
        return
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(out, encoding="utf-8")
    data = OUT.read_bytes()
    print(f"Wrote {OUT.relative_to(ROOT)}: {len(data):,} bytes, SHA-256 {sha(data)}")
    print(f"Inlined {counts[0]} stylesheets, {counts[1]} scripts, {counts[2]} images ({len(manifest)} source files).")


if __name__ == "__main__":
    main()
